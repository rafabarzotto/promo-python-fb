-- PROCEDURE PARA ATIVAR
CREATE OR ALTER PROCEDURE SP_ATIVAR_PROMO_SECAO (VAR_SEC INTEGER)
AS
BEGIN
    -- Ativa a promoção para os produtos da seção que possuem preço promocional > 0
    UPDATE PRODUTO 
    SET PROMO_ATIVA = 'S'
    WHERE COD_SEC = :VAR_SEC 
      AND PRECO_PROMOCAO > 0;
END^

-- PROCEDURE PARA DESATIVAR
CREATE OR ALTER PROCEDURE SP_DESATIVAR_PROMO_SECAO (VAR_SEC INTEGER)
AS
BEGIN
    -- Desativa a promoção para todos os produtos da seção
    UPDATE PRODUTO 
    SET PROMO_ATIVA = 'N'
    WHERE COD_SEC = :VAR_SEC;
END^
