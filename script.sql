-- 1. PROCEDURE PARA VERIFICAR E ATIVAR
CREATE OR ALTER PROCEDURE SP_ROTINA_ATIVAR_PROMO
AS
DECLARE VARIABLE VAR_SEC INTEGER;
DECLARE VARIABLE VAR_DIA_SEM INTEGER;
BEGIN
    VAR_DIA_SEM = EXTRACT(WEEKDAY FROM CURRENT_DATE);

    -- Busca regras que batem com hoje (Data Fixa OU Dia da Semana) e estão inativas
    FOR SELECT COD_SEC FROM REGRAS_PROMOCAO 
        WHERE STATUS = 'NORMAL' 
        AND (DATA_FIXA = CURRENT_DATE OR DIAS_SEMANA LIKE '%' || :VAR_DIA_SEM || '%')
        INTO :VAR_SEC
    DO
    BEGIN
        -- Ativa os produtos daquela seção
        UPDATE PRODUTO SET PROMO_ATIVA = 'S' 
        WHERE COD_SEC = :VAR_SEC AND PRECO_PROMOCAO > 0;
        
        -- Marca a regra como ATIVA
        UPDATE REGRAS_PROMOCAO SET STATUS = 'PROMO' WHERE COD_SEC = :VAR_SEC;
    END
END^

-- 2. PROCEDURE PARA VERIFICAR E DESATIVAR
CREATE OR ALTER PROCEDURE SP_ROTINA_DESATIVAR_PROMO
AS
DECLARE VARIABLE VAR_SEC INTEGER;
DECLARE VARIABLE VAR_DIA_SEM INTEGER;
BEGIN
    VAR_DIA_SEM = EXTRACT(WEEKDAY FROM CURRENT_DATE);

    -- Busca regras que estão como 'PROMO' mas NÃO deveriam estar ativas hoje
    FOR SELECT COD_SEC FROM REGRAS_PROMOCAO 
        WHERE STATUS = 'PROMO'
        AND (
            (DATA_FIXA IS NOT NULL AND DATA_FIXA <> CURRENT_DATE) OR 
            (DIAS_SEMANA IS NOT NULL AND DIAS_SEMANA NOT LIKE '%' || :VAR_DIA_SEM || '%')
        )
        INTO :VAR_SEC
    DO
    BEGIN
        -- Desativa os produtos
        UPDATE PRODUTO SET PROMO_ATIVA = 'N' WHERE COD_SEC = :VAR_SEC;
        
        -- Volta a regra para status NORMAL
        UPDATE REGRAS_PROMOCAO SET STATUS = 'NORMAL' WHERE COD_SEC = :VAR_SEC;
    END
END^
