-- PROCEDURE PARA ATIVAR
CREATE OR ALTER PROCEDURE SP_ATIVAR_PROMO_SECAO (VAR_SEC INTEGER)
AS
BEGIN
    -- Salva o preço original e aplica o promocional
    UPDATE PRODUTO 
    SET PRECO_NORMAL = PRECO_VAREJO,
        PRECO_VAREJO = PRECO_PROMOCAO
    WHERE COD_SEC = :VAR_SEC 
      AND PRECO_PROMOCAO > 0 
      AND (PRECO_NORMAL IS NULL OR PRECO_NORMAL = 0); -- Evita sobrescrever se já estiver em promo
END^

-- PROCEDURE PARA DESATIVAR
CREATE OR ALTER PROCEDURE SP_DESATIVAR_PROMO_SECAO (VAR_SEC INTEGER)
AS
BEGIN
    -- Volta o preço original e limpa o backup
    UPDATE PRODUTO 
    SET PRECO_VAREJO = PRECO_NORMAL,
        PRECO_NORMAL = NULL
    WHERE COD_SEC = :VAR_SEC 
      AND PRECO_NORMAL IS NOT NULL;
END^

SET TERM ; ^
